export function toThaiError(err: unknown): string {
  if (!err) return 'เกิดข้อผิดพลาดที่ไม่ทราบสาเหตุ'

  const e = err as Partial<PostgrestError> & { message?: string; code?: string; hint?: string }
  const raw = String(e.message ?? err)

  // ข้อความภาษาไทยจากฐานข้อมูล ใช้ได้เลย ตรงกว่าที่เราจะเขียนแทน
  if (isThai(raw)) {
    return e.hint && isThai(e.hint) ? `${raw} (${e.hint})` : raw
  }

  if (e.code && BY_CODE[e.code]) {
    const base = BY_CODE[e.code]
    // details ของ PostgreSQL มักบอกชื่อคอลัมน์ที่ชน ซึ่งช่วยผู้ใช้ได้จริง
    const detail = (e as { details?: string }).details
    return detail ? `${base}\n(${detail})` : base
  }

  for (const rule of BY_TEXT) {
    if (rule.match.test(raw)) return rule.message
  }

  // ไม่รู้จัก — แสดงของจริงไป ดีกว่ากลบจนหาสาเหตุไม่ได้
  return raw
}
